import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { McpPackageOptions, McpPackageResult } from "./types.js";

/**
 * 1-Click Multi-Target Packager & Dockerizer for Model Context Protocol servers
 */
// biome-ignore lint/complexity/noStaticOnlyClass: Packager utility class
export class McpServerPackager {
  public static package(options: McpPackageOptions): McpPackageResult {
    const targetDir = resolve(options.targetDir);
    const language = options.language || "typescript";
    const serverName = options.serverName.toLowerCase().replace(/[^a-z0-9_-]/g, "-");
    const port = options.port || 8080;
    const envVars = options.envVars || [];

    // 1. Generate Multi-Stage Minimal Dockerfile
    const dockerfile =
      language === "typescript"
        ? McpServerPackager.generateTypeScriptDockerfile(options)
        : McpServerPackager.generatePythonDockerfile(options);

    // 2. Client Configs
    const nodeEntry = options.entrypoint || "dist/index.js";
    const claudeDesktopConfig = {
      mcpServers: {
        [serverName]: {
          command: language === "typescript" ? "node" : "python",
          args: [
            language === "typescript" ? `${targetDir.replace(/\\/g, "/")}/${nodeEntry}` : "-m",
            language === "typescript" ? "" : `${serverName.replace(/-/g, "_")}.server`,
          ].filter(Boolean),
          env: Object.fromEntries(envVars.map((k) => [k, `YOUR_${k}_HERE`])),
        },
      },
    };

    const cursorConfig = {
      mcpServers: {
        [serverName]: {
          command: language === "typescript" ? "node" : "python",
          args: [
            language === "typescript" ? `${targetDir.replace(/\\/g, "/")}/${nodeEntry}` : "-m",
            language === "typescript" ? "" : `${serverName.replace(/-/g, "_")}.server`,
          ].filter(Boolean),
        },
      },
    };

    const antigravityConfig = {
      mcpServers: {
        [serverName]: {
          command: language === "typescript" ? "node" : "python",
          args: [
            language === "typescript" ? `${targetDir.replace(/\\/g, "/")}/${nodeEntry}` : "-m",
            language === "typescript" ? "" : `${serverName.replace(/-/g, "_")}.server`,
          ].filter(Boolean),
        },
      },
    };

    // 3. MCP Tool Registry Manifest (mcp.json)
    const registryManifest = {
      $schema: "https://modelcontextprotocol.io/schemas/registry/v1/manifest.json",
      name: serverName,
      version: "0.1.0",
      description: "Automated MCP Server packaged with mcp-builder-kit",
      publisher: "RitualDev-Lab",
      repository: `https://github.com/RitualDev-Lab/${serverName}`,
      transport: {
        stdio: {
          command: language === "typescript" ? "node" : "python",
          args: [nodeEntry],
        },
        sse: {
          url: `http://localhost:${port}/sse`,
        },
      },
      tags: ["mcp", "ai-agent", serverName],
    };

    // Write Files
    const writtenFiles: string[] = [];
    if (!existsSync(targetDir)) {
      mkdirSync(targetDir, { recursive: true });
    }

    const dockerfilePath = join(targetDir, "Dockerfile");
    writeFileSync(dockerfilePath, dockerfile, "utf8");
    writtenFiles.push("Dockerfile");

    const manifestPath = join(targetDir, "mcp.json");
    writeFileSync(manifestPath, JSON.stringify(registryManifest, null, 2), "utf8");
    writtenFiles.push("mcp.json");

    const claudePath = join(targetDir, "claude_desktop_config.json");
    writeFileSync(claudePath, JSON.stringify(claudeDesktopConfig, null, 2), "utf8");
    writtenFiles.push("claude_desktop_config.json");

    return {
      dockerfile,
      claudeDesktopConfig,
      cursorConfig,
      antigravityConfig,
      registryManifest,
      writtenFiles,
    };
  }

  private static generateTypeScriptDockerfile(options: McpPackageOptions): string {
    const port = options.port || 8080;
    return `
# Multi-stage production Dockerfile for TypeScript MCP Server
# Generated by mcp-builder-kit
FROM node:22-alpine AS builder

WORKDIR /app
COPY package.json pnpm-lock.yaml* ./
RUN npm install -g pnpm && pnpm install --frozen-lockfile || npm install

COPY . .
RUN npm run build || true

FROM node:22-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=${port}

COPY --from=builder /app/package.json ./
COPY --from=builder /app/dist ./dist
COPY --from=builder /app/node_modules ./node_modules

EXPOSE ${port}
CMD ["node", "dist/index.js"]
`.trim();
  }

  private static generatePythonDockerfile(options: McpPackageOptions): string {
    const port = options.port || 8080;
    const serverName = options.serverName.replace(/[^a-z0-9_]/g, "_");
    return `
# Production Dockerfile for Python FastMCP Server
# Generated by mcp-builder-kit
FROM python:3.11-slim

WORKDIR /app
ENV PYTHONUNBUFFERED=1
ENV PORT=${port}

COPY pyproject.toml README.md ./
COPY ${serverName}/ ./${serverName}/

RUN pip install --no-cache-dir --upgrade pip && \\
    pip install --no-cache-dir .

EXPOSE ${port}
CMD ["python", "-m", "${serverName}.server"]
`.trim();
  }
}
